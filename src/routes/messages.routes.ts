import { Router } from "express";
import { z } from "zod";
import multer from "multer";
import * as c from "../controllers/messages.controller";
import { authenticate } from "../middleware/authenticate";
import { validateBody } from "../middleware/validate";
import { messageSchema } from "../validators/message.schemas";

const r = Router();
const attachmentUpload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 50 * 1024 * 1024, files: 1 } });
r.get("/conversations", authenticate, c.conversations);
r.post("/conversations", authenticate, validateBody(z.object({ username: z.string().trim().min(3).max(30) })), c.createConversation);
r.post("/groups", authenticate, validateBody(z.object({ name: z.string().trim().min(1).max(80), usernames: z.array(z.string().trim().min(3).max(30)).max(99).default([]) })), c.createGroup);
r.get("/conversations/:id/messages", authenticate, c.list);
r.put("/conversations/:id/typing", authenticate, validateBody(z.object({ typing: z.boolean() })), c.typing);
r.get("/conversations/:id/typing", authenticate, c.typingStatus);
r.post("/conversations/:id/messages", authenticate, validateBody(messageSchema), c.send);
r.post("/conversations/:id/attachments", authenticate, attachmentUpload.single("file"), c.uploadAttachment);
r.post("/conversations/:id/attachments/message", authenticate, validateBody(z.object({ path: z.string().min(1), name: z.string().min(1).max(255), mimeType: z.string().min(1).max(120), sizeBytes: z.number().int().positive().max(52428800), messageType: z.enum(["image","video","file","voice"]), body: z.string().max(5000).optional() })), c.sendAttachment);
r.post("/conversations/:id/messages/:messageId/reactions", authenticate, validateBody(z.object({ emoji: z.string().min(1).max(16) })), c.react);
r.delete("/conversations/:id/messages/:messageId", authenticate, c.deleteMessage);
r.post("/conversations/:id/messages/:messageId/hide", authenticate, c.hideMessage);
r.post("/conversations/:id/members", authenticate, validateBody(z.object({ username: z.string().trim().min(3).max(30) })), c.addMember);
r.delete("/conversations/:id/group", authenticate, c.deleteGroup);
r.post("/conversations/:id/clear", authenticate, c.clearHistory);
r.post("/conversations/:id/leave", authenticate, c.leaveGroup);
r.post("/conversations/:id/call-signals", authenticate, validateBody(z.object({ recipientId: z.string().uuid(), callId: z.string().uuid(), signalType: z.enum(["offer","answer","ice","hangup","reject"]), payload: z.unknown().optional() })), c.signal);
r.get("/conversations/:id/call-signals", authenticate, c.signals);
export default r;
